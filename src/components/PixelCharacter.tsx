interface Props {
  size?: number;
}

export default function PixelCharacter({ size = 64 }: Props) {
  const px = size / 32;
  return (
    <View style={{ width: size, height: size }}>
      <Svg width={size} height={size} viewBox="0 0 32 32">
        {SPRITE.map((row, y) =>
          row.split('').map((cell, x) => {
            if (cell === '0') return null;
            return (
              <Rect
                key={`${y}-${x}`}
                x={x}
                y={y}
                width={1}
                height={1}
                fill={P[cell]}
              />
            );
          })
        )}
      </Svg>
    </View>
  );
}
